test('submits exactly one encrypted aes128gcm Web Push request', async () => {
  const receiver = await crypto.subtle.generateKey({ name: 'ECDH', namedCurve: 'P-256' }, true, ['deriveBits'])
  const vapid = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify'])
  const p256dh = new Uint8Array(await crypto.subtle.exportKey('raw', receiver.publicKey))
  const publicKey = new Uint8Array(await crypto.subtle.exportKey('raw', vapid.publicKey))
  const encoded = (bytes: Uint8Array) => btoa(String.fromCharCode(...bytes)).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/g, '')
  let calls = 0
  const subscription = { endpoint: 'https://push.example.test/subscription', keys: { p256dh: encoded(p256dh), auth: encoded(crypto.getRandomValues(new Uint8Array(16))) } }
  const message = { title: 'Nová akce', body: 'Podrobnosti', url: 'https://jednadvacet.org/kalendar' }
  const now = new Date('2026-10-04T12:00:00Z')
  const result = await sendWebPush(subscription, message, { privateKey: vapid.privateKey, publicKey: encoded(publicKey), subject: 'mailto:notifications@jednadvacet.org' }, async (_url, request) => {
    calls += 1
    assert.ok(request)
    const headers = new Headers(request.headers)
    assert.equal(headers.get('content-encoding'), 'aes128gcm')
    assert.equal(headers.get('content-type'), 'application/octet-stream')
    assert.equal(headers.get('ttl'), '60')
    assert.equal(request.redirect, 'manual')
    assert.ok(request.signal instanceof AbortSignal)
    const authorization = headers.get('authorization')!
    const [jwt, key] = authorization.slice('vapid t='.length).split(', k=')
    assert.equal(key, encoded(publicKey))
    const [header, claims, signature] = jwt!.split('.')
    assert.deepEqual(JSON.parse(Buffer.from(header!, 'base64url').toString()), { typ: 'JWT', alg: 'ES256' })
    assert.deepEqual(JSON.parse(Buffer.from(claims!, 'base64url').toString()), { aud: 'https://push.example.test', sub: 'mailto:notifications@jednadvacet.org', exp: now.getTime() / 1000 + 23 * 3600 })
    assert.equal(verify('sha256', Buffer.from(`${header}.${claims}`), { key: createPublicKey({ key: { ...await crypto.subtle.exportKey('jwk', vapid.publicKey) }, format: 'jwk' }), dsaEncoding: 'ieee-p1363' }, Buffer.from(signature!, 'base64url')), true)
    // Independent Node receiver: no production derivation helpers or HKDF Web Crypto.
    const body = Buffer.from(request.body as Uint8Array)
    assert.equal(body.readUInt32BE(16), 4096)
    assert.equal(body[20], 65)
    const ecdh = createECDH('prime256v1')
    ecdh.setPrivateKey(Buffer.from((await crypto.subtle.exportKey('jwk', receiver.privateKey)).d!, 'base64url'))
    const shared = ecdh.computeSecret(body.subarray(21, 86))
    const ikm = hkdfSync('sha256', shared, Buffer.from(subscription.keys.auth, 'base64url'), Buffer.concat([Buffer.from('WebPush: info\0'), Buffer.from(p256dh), body.subarray(21, 86)]), 32)
    const cek = hkdfSync('sha256', Buffer.from(ikm), body.subarray(0, 16), Buffer.from('Content-Encoding: aes128gcm\0'), 16)
    const nonce = hkdfSync('sha256', Buffer.from(ikm), body.subarray(0, 16), Buffer.from('Content-Encoding: nonce\0'), 12)
    const decipher = createDecipheriv('aes-128-gcm', Buffer.from(cek), Buffer.from(nonce))
    decipher.setAuthTag(body.subarray(-16))
    const plaintext = Buffer.concat([decipher.update(body.subarray(86, -16)), decipher.final()])
    assert.equal(plaintext.at(-1), 2)
    assert.deepEqual(JSON.parse(plaintext.subarray(0, -1).toString()), message)
    return new Response(null, { status: 201 })
  }, now)
  assert.deepEqual(result, { attempted: true, status: 'submitted', httpStatus: 201 })
  assert.equal(calls, 1)
})

test('fresh entropy and UTF-8 byte limits at the protocol boundary', async () => {
  const message = { title: 'Test', body: 'ě', url: '/kalendar' }
  const a = await encryptWebPushPayload(rfcSubscription, message)
  const b = await encryptWebPushPayload(rfcSubscription, message)
  assert.notDeepEqual(a.body.slice(0, 16), b.body.slice(0, 16))
  assert.notDeepEqual(a.body.slice(21, 86), b.body.slice(21, 86))
  assert.equal((await encryptWebPushPayload(rfcSubscription, new Uint8Array(3993))).body.length, 4096)
  await assert.rejects(encryptWebPushPayload(rfcSubscription, new Uint8Array(3994)))
  await assert.rejects(encryptWebPushPayload(rfcSubscription, { ...message, body: 'ě'.repeat(2000) }))
})

test('local validation never fetches; transport errors and every status are fixed privacy-safe outcomes', async () => {
  const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify'])
  const config = { privateKey: pair.privateKey, publicKey: Buffer.from(await crypto.subtle.exportKey('raw', pair.publicKey)).toString('base64url'), subject: 'mailto:notifications@jednadvacet.org' }
  const message = { title: 'Test', body: 'Test', url: '/kalendar' }
  let calls = 0
  const forbidden: typeof fetch = async () => { calls++; throw new TypeError('private sentinel') }
  for (const input of [{ ...rfcSubscription, endpoint: 'not a URL' }, { ...rfcSubscription, keys: { ...rfcSubscription.keys, auth: 'bad' } }]) {
    assert.deepEqual(await sendWebPush(input, message, config, forbidden), { attempted: false, status: 'invalid-request' })
  }
  for (const subject of ['mailto:a@b\n', 'https://user:password@example.test', 'invalid']) assert.deepEqual(await sendWebPush(rfcSubscription, message, { ...config, subject }, forbidden), { attempted: false, status: 'invalid-request' })
  assert.deepEqual(await sendWebPush(rfcSubscription, message, config, forbidden, new Date(NaN)), { attempted: false, status: 'invalid-request' })
  const other = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify'])
  assert.deepEqual(await sendWebPush(rfcSubscription, message, { ...config, privateKey: other.privateKey }, forbidden), { attempted: false, status: 'invalid-request' })
  assert.equal(calls, 0)
  for (const [code, status] of [[201, 'submitted'], [404, 'stale-endpoint'], [410, 'stale-endpoint'], [429, 'rate-limited'], [500, 'provider-5xx'], [503, 'provider-5xx'], [401, 'auth'], [403, 'auth'], [400, 'invalid-request'], [302, 'invalid-request']] as const) {
    assert.deepEqual(await sendWebPush(rfcSubscription, message, config, async () => ({ status: code, text: () => { throw new Error('must not read body') } }) as unknown as Response), { attempted: true, status, httpStatus: code })
  }
  for (const error of [new TypeError('private'), new Error('private'), new DOMException('private', 'AbortError')]) assert.deepEqual(await sendWebPush(rfcSubscription, message, config, async () => { throw error }), { attempted: true, status: 'transport' })
})

test('push transport diagnostics distinguish provider rejection from timeout without logging private material', async t => {
  const warning = t.mock.method(console, 'warn', () => {})
  const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify'])
  const config = { privateKey: pair.privateKey, publicKey: Buffer.from(await crypto.subtle.exportKey('raw', pair.publicKey)).toString('base64url'), subject: 'https://jednadvacet.org' }
  const message = { title: 'Test', body: 'Test', url: '/' }
  await sendWebPush(rfcSubscription, message, config, async () => new Response('private response', { status: 503 }))
  await sendWebPush(rfcSubscription, message, config, async () => { throw new TypeError('private transport detail') })
  assert.deepEqual(warning.mock.calls.map(call => call.arguments), [
    ['[notifications] Web Push provider rejected a request', { httpStatus: 503 }],
    ['[notifications] Web Push transport failed', { timedOut: false, errorType: 'TypeError' }],
  ])
})

test('send aborts a stalled transport after its bounded timeout', async (t) => {
  const warning = t.mock.method(console, 'warn', () => {})
  t.mock.timers.enable({ apis: ['setTimeout'] })
  const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify'])
  let started!: () => void
  const ready = new Promise<void>(resolve => { started = resolve })
  const pending = sendWebPush(rfcSubscription, { title: 'Test', body: 'Test', url: '/' }, { privateKey: pair.privateKey, publicKey: Buffer.from(await crypto.subtle.exportKey('raw', pair.publicKey)).toString('base64url'), subject: 'mailto:a@example.test' }, async (_url, request) => new Promise((_resolve, reject) => {
    request!.signal!.addEventListener('abort', () => reject(new DOMException('Timeout', 'AbortError')), { once: true })
    started()
  }))
  await ready
  t.mock.timers.tick(10_000)
  assert.deepEqual(await pending, { attempted: true, status: 'transport' })
  assert.deepEqual(warning.mock.calls.map(call => call.arguments), [['[notifications] Web Push transport failed', { timedOut: true, errorType: 'AbortError' }]])
})
